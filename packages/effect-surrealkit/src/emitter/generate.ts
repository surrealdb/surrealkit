/**
 * Schema document v2 → Effect modules.
 *
 * `generate` decodes the document and options strictly, refuses error
 * diagnostics the project has not acknowledged, lowers every table to its
 * per-operation contract and prints one module set. Output is a pure function
 * of (document, options, emitter version): no timestamps, no physical
 * namespace or database names, stable ordering.
 */
import { Data, Effect } from 'effect';

import { semanticDigest } from './canonical.js';
import { compare, IdRegistry, ModuleScope, profileFor } from './context.js';
import {
	type DocumentError,
	decodeDocument,
	type SchemaDocument,
	type SurrealFunction,
} from './document.js';
import { printKind } from './kinds.js';
import { functionIdentifier, propertyKey } from './names.js';
import {
	decodeOptions,
	type EmitterOptions,
	type OptionsError,
} from './options.js';
import { printTable } from './tables.js';
import { EMITTER_VERSION, PEER_VERSIONS } from './version.js';

export interface GeneratedFile {
	/** Path relative to the output directory, `/`-separated. */
	readonly path: string;
	readonly content: string;
}

export interface GenerateResult {
	readonly files: ReadonlyArray<GeneratedFile>;
	readonly warnings: ReadonlyArray<string>;
}

/** The document and options decoded, but generation is not possible. */
export class GenerateError extends Data.TaggedError('GenerateError')<{
	readonly message: string;
}> {}

const fail = (message: string): never => {
	throw new GenerateError({ message });
};

export interface GenerateHooks {
	/**
	 * Lowercase hex SHA-256 of a UTF-8 string. When given, the document's
	 * `semanticDigest` is recomputed and a mismatch (a hand-edited or
	 * truncated document) fails generation.
	 */
	readonly sha256?: (text: string) => string;
}

const RESERVED_FILES = new Set(['ids', 'functions', 'manifest', 'index']);

const json = (value: unknown): string => JSON.stringify(value);
const jsonList = (values: ReadonlyArray<string>): string =>
	`[${values.map((value) => JSON.stringify(value)).join(', ')}]`;

const header = (digest: string): string =>
	[
		'// Generated by effect-surrealkit from a SurrealKit schema document. Do not edit.',
		`// semanticDigest: ${digest}`,
	].join('\n');

const imports = (
	body: string,
	ids: ReadonlySet<string>,
	fromIds: boolean,
	ext: string,
): string => {
	const lines: string[] = [];
	if (/\bSchema\./.test(body)) lines.push('import { Schema } from "effect";');
	if (/\bSurrealSchema\./.test(body)) {
		lines.push('import * as SurrealSchema from "effect-surrealkit";');
		// The declarations of this module name SDK types (DateTime, RecordId…). An
		// import of `surrealdb` here makes the program resolve it from the
		// consumer, so declaration emit can name them as "surrealdb" rather than
		// through a path into effect-surrealkit's own dependencies (TS2742/TS2883
		// under pnpm). It binds nothing and is erased.
		lines.push('import type {} from "surrealdb";');
	}
	if (fromIds && ids.size > 0) {
		lines.push(
			`import { ${[...ids].sort(compare).join(', ')} } from "./ids${ext}";`,
		);
	}
	return lines.join('\n');
};

const assemble = (digest: string, importLines: string, body: string): string =>
	`${[header(digest), importLines, body].filter((part) => part.length > 0).join('\n\n')}\n`;

const gateDiagnostics = (
	document: SchemaDocument,
	options: EmitterOptions,
): void => {
	const acknowledged = options.acknowledge ?? {};
	const blocking = document.diagnostics.filter(
		(diagnostic) =>
			diagnostic.severity === 'error' &&
			acknowledged[diagnostic.code] === undefined,
	);
	if (blocking.length > 0) {
		const listed = blocking
			.map((d) => {
				const where = [d.table, d.field?.join('.'), d.function]
					.filter(Boolean)
					.join(' ');
				return `  ${d.code}${where === '' ? '' : ` (${where})`}: ${d.reason}`;
			})
			.join('\n');
		fail(
			`the schema document has error diagnostics; fix them or acknowledge each code with a reason in the emitter options (acknowledge):\n${listed}`,
		);
	}
};

const checkNames = (
	document: SchemaDocument,
	registry: IdRegistry,
): ReadonlyMap<string, string> => {
	const files = new Map<string, string>();
	const exports = new Map<string, string>();
	const claim = (
		map: Map<string, string>,
		name: string,
		owner: string,
		what: string,
	) => {
		const previous = map.get(name);
		if (previous !== undefined && previous !== owner) {
			fail(
				`${what} \`${name}\` would be generated for both ${previous} and ${owner}; give one of them another name in the emitter options (names)`,
			);
		}
		map.set(name, owner);
	};
	for (const table of document.tables) {
		const owner = `table \`${table.name}\``;
		const file = registry.file(table.name);
		if (RESERVED_FILES.has(file)) {
			fail(
				`table \`${table.name}\` would be written to ${file}.ts, which the emitter reserves`,
			);
		}
		claim(files, file, owner, 'module');
		const pascal = registry.pascal(table.name);
		for (const suffix of [
			'',
			'Row',
			'Id',
			'Create',
			'Merge',
			'Content',
			'Patch',
			'Fields',
			'Table',
			'Edge',
		]) {
			claim(exports, `${pascal}${suffix}`, owner, 'export');
		}
	}
	for (const fn of document.functions) {
		claim(
			exports,
			functionIdentifier(fn.name),
			`function \`${fn.name}\``,
			'export',
		);
	}
	return exports;
};

const printIds = (
	registry: IdRegistry,
	options: EmitterOptions,
	document: SchemaDocument,
	warnings: string[],
): string => {
	const scope = new ModuleScope(registry, warnings);
	const keys = new Map(
		document.tables.map((table) => [table.name, table.idKey]),
	);
	const lines: string[] = [];
	for (const [table, name] of registry.tables) {
		const idKey = keys.get(table);
		const brand = `Schema.brand(${json(`${options.store}/${table}`)})`;
		// A key is checked against the SDK value it decodes from (`sameKey`), so
		// datetimes in it stay SDK values whatever the datetime profile: the
		// lossy Effect DateTime would differ from every valid key.
		const profile = {
			...profileFor(options, `${table}.id`),
			datetime: 'sdk' as const,
		};
		const key =
			idKey === undefined
				? ''
				: `, { key: ${printKind(idKey, { scope, profile, location: `${table}.id` })} }`;
		const note = registry.isDefined(table)
			? ''
			: ' (referenced, not defined in this schema)';
		lines.push(
			`/** Record id of \`${table}\`${note}. */`,
			`export const ${name} = SurrealSchema.RecordIdFor(${json(table)}${key}).pipe(${brand});`,
			`export type ${name} = typeof ${name}.Type;`,
			'',
		);
	}
	for (const [name, tables] of registry.unions) {
		const tagged = IdRegistry.tagged(name);
		const spelled = `record<${tables.join(' | ')}>`;
		lines.push(
			`/** \`${spelled}\`. */`,
			`export const ${name} = Schema.Union([${tables.map((t) => registry.table(t)).join(', ')}]);`,
			`export type ${name} = typeof ${name}.Type;`,
			`/** \`${spelled}\` as \`{ _tag, id }\`, to match on the table. An application representation; never stored. */`,
			`export const ${tagged} = SurrealSchema.taggedRecordId({ ${tables
				.map((t) => `${propertyKey(t)}: ${registry.table(t)}`)
				.join(', ')} });`,
			`export type ${tagged} = typeof ${tagged}.Type;`,
			'',
		);
	}
	return lines.join('\n').trimEnd();
};

const printFunction = (
	fn: SurrealFunction,
	scope: ModuleScope,
	options: EmitterOptions,
): string => {
	const ctx = (location: string) => ({
		scope,
		profile: profileFor(options, fn.name),
		location,
	});
	const args = fn.args.map((arg) => {
		const code = printKind(arg.kind, ctx(`${fn.name}($${arg.name})`));
		if (!arg.optional) return code;
		return arg.omittable
			? `Schema.optional(${code})`
			: `Schema.UndefinedOr(${code})`;
	});
	const returns =
		fn.returns === undefined
			? 'Schema.Unknown'
			: printKind(fn.returns, ctx(`${fn.name} -> return`));
	const doc =
		fn.comment === undefined
			? `\`${fn.name}\``
			: `\`${fn.name}\`: ${fn.comment.replace(/\*\//g, '* /')}`;
	return [
		`/** ${doc} */`,
		`export const ${functionIdentifier(fn.name)} = SurrealSchema.fn({`,
		`\tname: ${json(fn.name)},`,
		`\targs: Schema.Tuple([${args.join(', ')}]),`,
		`\treturns: ${returns},`,
		'});',
	].join('\n');
};

const printManifest = (
	document: SchemaDocument,
	options: EmitterOptions,
): string => {
	const { generator, engine, adapter, source } = document.provenance;
	const sourceLines =
		source.kind === 'compile'
			? [
					`\t\tkind: "compile",`,
					`\t\tmodules: ${jsonList(source.modules)},`,
				]
			: [`\t\tkind: "introspect",`];
	return [
		'/** What these modules were generated from, and how. */',
		'export const manifest = {',
		`\tstore: ${json(options.store)},`,
		`\tsemanticDigest: ${json(document.semanticDigest)},`,
		`\temitter: { name: "effect-surrealkit", version: ${json(EMITTER_VERSION)} },`,
		`\tprofile: { int: ${json(options.int ?? 'safe-number')}, datetime: ${json(options.datetime ?? 'sdk')} },`,
		`\tpeers: { effect: ${json(PEER_VERSIONS.effect)}, surrealdb: ${json(PEER_VERSIONS.surrealdb)} },`,
		'\tsource: {',
		...sourceLines,
		`\t\tsurrealkit: ${json(generator.version)},`,
		...(generator.commit === undefined
			? []
			: [`\t\tcommit: ${json(generator.commit)},`]),
		`\t\tengine: ${json(engine.version)},`,
		`\t\tadapter: ${json(adapter)},`,
		'\t},',
		`\ttables: ${jsonList(document.tables.map((table) => table.name))},`,
		`\tfunctions: ${jsonList(document.functions.map((fn) => fn.name))},`,
		'} as const;',
	].join('\n');
};

/** Generates the module set from an already decoded document and options. */
export const emit = (
	document: SchemaDocument,
	options: EmitterOptions,
	hooks: GenerateHooks = {},
): GenerateResult => {
	gateDiagnostics(document, options);
	if (hooks.sha256 !== undefined) {
		const actual = semanticDigest(
			document as unknown as Record<string, unknown>,
			hooks.sha256,
		);
		if (actual !== document.semanticDigest) {
			fail(
				`semanticDigest mismatch: the document declares ${document.semanticDigest} but its semantic content hashes to ${actual}; regenerate it with surrealkit instead of editing it`,
			);
		}
	}
	const registry = new IdRegistry(document, options.names ?? {});
	const ext = options.importExtension ?? '.js';
	const claimed = checkNames(document, registry);
	const warnings: string[] = document.diagnostics
		.filter((diagnostic) => diagnostic.severity === 'warning')
		.map((d) => {
			const where = [d.table, d.field?.join('.'), d.function]
				.filter(Boolean)
				.join(' ');
			return `document: ${d.code}${where === '' ? '' : ` (${where})`}: ${d.reason}`;
		});
	const digest = document.semanticDigest;
	const tables = [...document.tables].sort((a, b) => compare(a.name, b.name));

	const relationsOf = (name: string) => {
		const ins: string[] = [];
		const outs: string[] = [];
		for (const table of tables) {
			if (table.type.kind !== 'relation') continue;
			if (table.type.in.includes(name)) ins.push(table.name);
			if (table.type.out.includes(name)) outs.push(table.name);
		}
		return { in: ins, out: outs };
	};

	const files: GeneratedFile[] = [];
	for (const table of tables) {
		const scope = new ModuleScope(registry, warnings);
		const body = printTable({
			table,
			scope,
			options,
			digest,
			relations: relationsOf(table.name),
		});
		const ownId = registry.table(table.name);
		const reexport = `export { ${ownId} } from "./ids${ext}";`;
		files.push({
			path: `${registry.file(table.name)}.ts`,
			content: assemble(
				digest,
				imports(body, scope.ids, true, ext),
				`${reexport}\n\n${body}`,
			),
		});
	}

	const functionScope = new ModuleScope(registry, warnings);
	const functions = [...document.functions].sort((a, b) =>
		compare(a.name, b.name),
	);
	const functionBody =
		functions.length === 0
			? 'export {};'
			: functions
					.map((fn) => printFunction(fn, functionScope, options))
					.join('\n\n');
	files.push({
		path: 'functions.ts',
		content: assemble(
			digest,
			imports(functionBody, functionScope.ids, true, ext),
			functionBody,
		),
	});

	// Printed last: every module above has registered the ids it uses. Ids of
	// tables that are referenced but not defined, and id unions, are exported
	// from ids.ts too, so they must not collide with any other export.
	const exported = new Map(claimed);
	for (const [table, name] of registry.tables) {
		if (registry.isDefined(table)) continue;
		const owner = exported.get(name);
		if (owner !== undefined) {
			fail(
				`export \`${name}\` would be generated for both ${owner} and the referenced table \`${table}\`; give one of them another name in the emitter options (names)`,
			);
		}
		exported.set(name, `the referenced table \`${table}\``);
	}
	for (const [name, first, other] of registry.conflicts) {
		fail(
			`export \`${name}\` would be generated for both record<${first.join(' | ')}> and record<${other.join(' | ')}>; give one of their tables another name in the emitter options (names)`,
		);
	}
	for (const [name, tables] of registry.unions) {
		for (const unionExport of [name, IdRegistry.tagged(name)]) {
			const owner = exported.get(unionExport);
			if (owner !== undefined) {
				fail(
					`export \`${unionExport}\` would be generated for both record<${tables.join(' | ')}> and ${owner}; give one of the tables another name in the emitter options (names)`,
				);
			}
		}
	}
	// Without tables there are no ids, and `export *` of a file with no export
	// is an error (TS2306), so the file says it is a module.
	const idsBody =
		printIds(registry, options, document, warnings) || 'export {};';
	files.push({
		path: 'ids.ts',
		content: assemble(
			digest,
			imports(idsBody, new Set(), false, ext),
			idsBody,
		),
	});

	const manifestBody = printManifest(document, options);
	files.push({
		path: 'manifest.ts',
		content: assemble(digest, '', manifestBody),
	});

	const barrel = [
		`export * from "./ids${ext}";`,
		...tables.map(
			(table) => `export * from "./${registry.file(table.name)}${ext}";`,
		),
		`export * from "./functions${ext}";`,
		`export { manifest } from "./manifest${ext}";`,
	].join('\n');
	files.push({ path: 'index.ts', content: assemble(digest, '', barrel) });

	files.sort((a, b) => compare(a.path, b.path));
	return { files, warnings: [...new Set(warnings)].sort(compare) };
};

/**
 * Decodes `document` (parsed JSON) and `options` strictly, then generates the
 * module set.
 */
export const generate = (
	document: unknown,
	options: unknown,
	hooks: GenerateHooks = {},
): Effect.Effect<
	GenerateResult,
	DocumentError | OptionsError | GenerateError
> =>
	Effect.gen(function* () {
		const decoded = yield* decodeDocument(document);
		const decodedOptions = yield* decodeOptions(options);
		return yield* Effect.try({
			try: () => emit(decoded, decodedOptions, hooks),
			catch: (error) =>
				error instanceof GenerateError
					? error
					: new GenerateError({
							message:
								error instanceof Error
									? error.message
									: String(error),
						}),
		});
	});
