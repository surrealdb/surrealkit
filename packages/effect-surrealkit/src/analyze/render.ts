/**
 * Typed statement modules from authored SurrealQL texts: one module per
 * scope plus an index. Pure and host-neutral; the `effect-surrealkit
 * statements` command reads the files, calls this and writes the result.
 */
import { Data, Effect } from 'effect';

import { type Analysis, analyzeSync } from './analyze.js';
import {
	AnalyzeError,
	type HoleDelimiters,
	holeDelimiters,
	lex,
} from './lexer.js';
import { analyzeTargets } from './targets.js';
import type { BindingUse, BindingUses } from './uses.js';

/** First line of every module {@link renderStatementModules} renders. */
export const STATEMENTS_MARK =
	'// Generated by effect-surrealkit from SurrealQL files. Do not edit.';

const NAME = /^[A-Za-z_][A-Za-z0-9_]*$/u;

const RESERVED: ReadonlySet<string> = new Set(
	(
		'await break case catch class const continue debugger default delete do ' +
		'else enum export extends false finally for function if implements import ' +
		'in instanceof interface let new null package private protected public ' +
		'return static super switch this throw true try typeof var void while ' +
		'with yield arguments eval'
	).split(' '),
);

/** One authored text: `<scope>/<name>.surql`, `name` without `.surql`. */
export interface StatementSourceFile {
	readonly name: string;
	readonly sql: string;
}

/** One scope: a directory of texts that becomes `<name>/statements.ts`. */
export interface StatementScope {
	readonly name: string;
	readonly files: ReadonlyArray<StatementSourceFile>;
	/**
	 * The tables and custom functions the schema declares. When given, a
	 * table or function a file of this scope names that is not declared, and
	 * that the same text does not create with `DEFINE TABLE` or `DEFINE
	 * FUNCTION`, is a problem. Names behind an open target are not checked.
	 */
	readonly declared?: DeclaredNames;
}

/** The tables and custom functions (`fn::…`) a schema declares. */
export interface DeclaredNames {
	readonly tables: ReadonlyArray<string>;
	readonly functions: ReadonlyArray<string>;
	/**
	 * What the schema says about each table and function, as
	 * `declaredNames(document)` (`effect-surrealkit/emitter`) reads it. When
	 * given, every use of a binding the analyzer finds must resolve (a field
	 * the table declares or accepts, an argument the function takes), and
	 * each part states, in `binds`, the simple kind of each binding whose
	 * every use resolves to the same one (`option<K>` when every use accepts
	 * NONE).
	 */
	readonly detail?: DeclaredDetail;
}

/** The schema detail of {@link DeclaredNames}: kinds as SurrealQL text. */
export interface DeclaredDetail {
	readonly tables: Readonly<Record<string, DeclaredTable>>;
	/** The kind text of each argument of each function, in order. */
	readonly functions: Readonly<Record<string, ReadonlyArray<string>>>;
}

export interface DeclaredTable {
	/**
	 * Each declared field (its path joined with `.`): its kind text, and
	 * `rejectsNone` when the engine rejects NONE assigned to it in every
	 * statement that can assign it (`CREATE`, `UPDATE` and `UPSERT`): a
	 * top-level field whose kind excludes NONE, without `DEFAULT`, `VALUE`
	 * or `COMPUTED`. Left out, nothing is refused for the field.
	 */
	readonly fields: Readonly<
		Record<
			string,
			{ readonly kind?: string; readonly rejectsNone?: boolean }
		>
	>;
	/** The table accepts fields it does not declare (it is schemaless). */
	readonly acceptsUndeclared: boolean;
	/** The kind text of the id key, when the schema declares one. */
	readonly idKey?: string;
}

export interface RenderStatementModulesInput {
	readonly scopes: ReadonlyArray<StatementScope>;
	/** Extension of the index module's imports; default `.js`. */
	readonly importExtension?: '.js' | '.ts';
	/** The literal delimiters of a hole; default `__` and `__`. */
	readonly holes?: HoleDelimiters;
}

/** A rendered module, at a path relative to the output directory. */
export interface StatementModule {
	readonly path: string;
	readonly content: string;
}

/** An analyzer warning on one file. */
export interface StatementWarning {
	readonly scope: string;
	readonly file: string;
	readonly line: number;
	readonly column: number;
	readonly code: string;
	readonly message: string;
	/** `<scope>/<file>.surql:<line>:<column>: <message> (<code>)`. */
	readonly text: string;
}

/**
 * Why a module could not be rendered. `analysis`: the analyzer rejected the
 * file (`line`, `column` and `code` set). `name`: the file name is not an
 * identifier, is a reserved word, or differs only in case from another in
 * its scope. `scope`: the same for the scope name (`file` absent).
 * `undeclared`: the file names a table or function its scope's `declared`
 * names do not include (`line` of the first use set), or, with `declared`
 * detail, a binding used as a field the table does not declare or accept,
 * or as an argument beyond the function's arguments (`line` of the use).
 */
export interface StatementProblem {
	readonly kind: 'analysis' | 'name' | 'scope' | 'undeclared';
	readonly scope: string;
	readonly file?: string;
	readonly line?: number;
	readonly column?: number;
	readonly code?: string;
	readonly message: string;
	/** The problem as the `statements` command prints it. */
	readonly text: string;
}

/** Every problem with the input; `message` holds one `text` per line. */
export class StatementModulesError extends Data.TaggedError(
	'StatementModulesError',
)<{
	readonly problems: ReadonlyArray<StatementProblem>;
	readonly message: string;
}> {}

export interface StatementModules {
	readonly files: ReadonlyArray<StatementModule>;
	readonly warnings: ReadonlyArray<StatementWarning>;
}

const checkName = (
	name: string,
	what: string,
	seen: Map<string, string>,
): string | undefined => {
	if (!NAME.test(name)) {
		return `${what} is not a JavaScript identifier of letters, digits and underscores`;
	}
	if (RESERVED.has(name)) return `${what} is a reserved word`;
	const folded = name.toLowerCase();
	const other = seen.get(folded);
	if (other !== undefined) {
		return `${what} differs only in case from ${JSON.stringify(other)}`;
	}
	seen.set(folded, name);
	return undefined;
};

/** A TypeScript template literal holding `text` exactly. */
const templateLiteral = (text: string): string =>
	`\`${text
		.replace(/\\/gu, '\\\\')
		.replace(/`/gu, '\\`')
		.replace(/\$\{/gu, '\\${')
		.replace(/\r/gu, '\\r')}\``;

const list = (values: ReadonlyArray<string>): string =>
	`[${values.map((value) => JSON.stringify(value)).join(', ')}]`;

const scopesField = (scopes: Analysis['holeScopes']): string =>
	`{ ${Object.entries(scopes)
		.map(
			([hole, scope]) =>
				`${JSON.stringify(hole)}: { bound: ${list(scope.bound)}, binds: ${list(scope.binds)} }`,
		)
		.join(', ')} }`;

const lines = (throwsAt: Analysis['throwsAt']): string => {
	const entries = Object.entries(throwsAt);
	return entries.length === 0
		? '{}'
		: `{ ${entries.map(([message, at]) => `${JSON.stringify(message)}: [${at.join(', ')}]`).join(', ')} }`;
};

const useEntry = (use: BindingUse): string =>
	use.kind === 'argument'
		? `{ kind: "argument", function: ${JSON.stringify(use.function)}, index: ${use.index}, line: ${use.line} }`
		: use.kind === 'key'
			? `{ kind: "key", table: ${JSON.stringify(use.table)}, line: ${use.line} }`
			: `{ kind: "field", table: ${JSON.stringify(use.table)}, field: ${JSON.stringify(use.field)}, ${use.role === undefined ? '' : `role: ${JSON.stringify(use.role)}, `}line: ${use.line} }`;

const usesField = (uses: BindingUses): string =>
	`{ ${Object.entries(uses)
		.map(
			([name, list]) =>
				`${JSON.stringify(name)}: [${list.map(useEntry).join(', ')}]`,
		)
		.join(', ')} }`;

const rejectsNoneField = (
	fields: Readonly<Record<string, RejectedNone>>,
): string =>
	`{ ${Object.entries(fields)
		.map(
			([name, at]) =>
				`${JSON.stringify(name)}: { table: ${JSON.stringify(at.table)}, field: ${JSON.stringify(at.field)}, kind: ${JSON.stringify(at.kind)} }`,
		)
		.join(', ')} }`;

const bindsField = (binds: Readonly<Record<string, string>>): string =>
	`{ ${Object.entries(binds)
		.map(
			([name, kind]) =>
				`${JSON.stringify(name)}: ${JSON.stringify(kind)}`,
		)
		.join(', ')} }`;

/** A simple kind's text: one a codec's stored type can be checked against. */
const SIMPLE =
	/^(?:string|bool|int|float|number|decimal|datetime|duration|uuid|record<[^<>|,\s]+>)$/u;

/** The simple kind a kind text is, `option<K>` read as `K`; else undefined. */
const simpleKind = (kind: string | undefined): string | undefined => {
	if (kind === undefined) return undefined;
	const inner = /^option<(.*)>$/u.exec(kind)?.[1] ?? kind;
	return SIMPLE.test(inner) ? inner : undefined;
};

/**
 * Whether NONE is acceptable to a use whose kind text is `kind`: comparing
 * a field with NONE always is; assigning to a field, or passing an
 * argument, only when its kind is `option<…>`; a record key never.
 */
const acceptsNone = (use: BindingUse, kind: string | undefined): boolean =>
	use.kind === 'field' && use.role !== 'assign'
		? true
		: use.kind !== 'key' &&
			kind !== undefined &&
			/^option<.*>$/u.test(kind);

/** How a problem names a use that does not resolve. */
type Resolved =
	| {
			readonly kind: 'kind';
			readonly text: string | undefined;
			/** The use is a field that rejects NONE; see {@link DeclaredTable}. */
			readonly rejectsNone?: boolean;
	  }
	| { readonly kind: 'problem'; readonly message: string }
	| { readonly kind: 'unchecked' };

/**
 * What one use resolves to in the schema: the kind text of what it is
 * used as (undefined when the schema gives none), a problem when it cannot
 * resolve, or `unchecked` for a table or function the schema does not
 * declare (reported elsewhere) or the text defines itself.
 */
const resolve = (use: BindingUse, detail: DeclaredDetail): Resolved => {
	if (use.kind === 'argument') {
		const args = Object.hasOwn(detail.functions, use.function)
			? detail.functions[use.function]
			: undefined;
		if (args === undefined) return { kind: 'unchecked' };
		return use.index < args.length
			? { kind: 'kind', text: args[use.index] }
			: {
					kind: 'problem',
					message: `passes argument ${use.index + 1} to \`${use.function}\`, which takes ${args.length === 1 ? '1 argument' : `${args.length} arguments`}`,
				};
	}
	const table = Object.hasOwn(detail.tables, use.table)
		? detail.tables[use.table]
		: undefined;
	if (table === undefined) return { kind: 'unchecked' };
	if (use.kind === 'key') return { kind: 'kind', text: table.idKey };
	if (Object.hasOwn(table.fields, use.field)) {
		const field = table.fields[use.field];
		return {
			kind: 'kind',
			text: field?.kind,
			rejectsNone: field?.rejectsNone === true,
		};
	}
	if (use.field === 'id')
		return { kind: 'kind', text: `record<${use.table}>` };
	return table.acceptsUndeclared
		? { kind: 'kind', text: undefined }
		: {
				kind: 'problem',
				message: `${use.role === 'assign' ? 'assigns' : 'compares'} \`${use.field}\` of \`${use.table}\`, which declares no such field`,
			};
};

/** The field a binding is assigned to that rejects NONE; see `Part`. */
interface RejectedNone {
	readonly table: string;
	readonly field: string;
	/** The field's kind text. */
	readonly kind: string;
}

/**
 * The uses that do not resolve in `detail`, the simple kind of each
 * binding whose every use resolves to the same one, and, for each binding
 * assigned to a field that rejects NONE, the first such field. With
 * `schemaChanges`, the text defines, alters or removes a table or field
 * itself, so the schema may not hold when its assignments run and no
 * field is recorded.
 */
const checkUses = (
	uses: BindingUses,
	detail: DeclaredDetail,
	schemaChanges: boolean,
): {
	readonly problems: ReadonlyArray<{
		readonly line: number;
		readonly message: string;
	}>;
	readonly binds: Readonly<Record<string, string>>;
	readonly rejectsNone: Readonly<Record<string, RejectedNone>>;
} => {
	const problems: Array<{ line: number; message: string }> = [];
	const binds: Record<string, string> = {};
	const rejectsNone: Record<string, RejectedNone> = {};
	for (const [name, list] of Object.entries(uses)) {
		const kinds = new Set<string | undefined>();
		let none = true;
		for (const use of list) {
			const resolved = resolve(use, detail);
			if (resolved.kind === 'problem') {
				problems.push({ line: use.line, message: resolved.message });
				kinds.add(undefined);
			} else if (resolved.kind === 'unchecked') kinds.add(undefined);
			else {
				kinds.add(simpleKind(resolved.text));
				if (!acceptsNone(use, resolved.text)) none = false;
				if (
					!schemaChanges &&
					use.kind === 'field' &&
					use.role === 'assign' &&
					resolved.rejectsNone === true &&
					resolved.text !== undefined &&
					!Object.hasOwn(rejectsNone, name)
				)
					rejectsNone[name] = {
						table: use.table,
						field: use.field,
						kind: resolved.text,
					};
			}
		}
		const [only] = kinds;
		if (kinds.size === 1 && only !== undefined)
			binds[name] = none ? `option<${only}>` : only;
	}
	return { problems, binds, rejectsNone };
};

/** Whether `sql` defines, alters or removes a table or a field. */
const changesSchema = (
	sql: string,
	holes: HoleDelimiters | undefined,
): boolean => {
	const tokens = lex(sql, holeDelimiters(holes)).tokens;
	return tokens.some(
		(token, i) =>
			token.kind === 'word' &&
			['DEFINE', 'ALTER', 'REMOVE'].includes(token.value.toUpperCase()) &&
			tokens[i + 1]?.kind === 'word' &&
			['TABLE', 'FIELD'].includes(
				(tokens[i + 1]?.value ?? '').toUpperCase(),
			),
	);
};

const renderConstant = (
	scope: string,
	name: string,
	analysis: Analysis,
	binds: Readonly<Record<string, string>> | undefined,
	rejectsNone: Readonly<Record<string, RejectedNone>> | undefined,
): string => {
	const file = `${scope}/${name}.surql`;
	const complete = analysis.kind === 'part' && analysis.holes.length === 0;
	const what = complete
		? 'part'
		: analysis.holes.length > 0
			? 'template'
			: 'fragment';
	const fields = [
		`name: ${JSON.stringify(`${scope}.${name}`)}`,
		`source: ${JSON.stringify(file)}`,
		...(complete ? [] : [`kind: ${JSON.stringify(analysis.kind)}`]),
		`sql: ${templateLiteral(analysis.sql)}`,
		...(complete ? [] : [`holes: ${list(analysis.holes)}`]),
		`free: ${list(analysis.free)}`,
		`defines: ${list(analysis.defines)}`,
		...(complete ? [] : [`provisional: ${analysis.provisional}`]),
		...(analysis.holes.length > 0
			? [`scopes: ${scopesField(analysis.holeScopes)}`]
			: []),
		`slots: ${analysis.slots}`,
		`throws: ${list(analysis.throws)}`,
		`throwsAt: ${lines(analysis.throwsAt)}`,
		...(complete
			? [
					`tables: { read: ${list(analysis.tables.read)}, written: ${list(analysis.tables.written)} }`,
					`functions: ${list(analysis.functions)}`,
					...(analysis.openTargets ? ['openTargets: true'] : []),
					...(Object.keys(analysis.uses).length > 0
						? [`uses: ${usesField(analysis.uses)}`]
						: []),
					...(binds !== undefined && Object.keys(binds).length > 0
						? [`binds: ${bindsField(binds)}`]
						: []),
					...(rejectsNone !== undefined &&
					Object.keys(rejectsNone).length > 0
						? [`rejectsNone: ${rejectsNoneField(rejectsNone)}`]
						: []),
				]
			: []),
	];
	return [
		`/** \`${file}\`: a ${what}. */`,
		`export const ${name} = ${complete ? '$statement.part' : '$analyze.text'}({`,
		...fields.map((field) => `\t${field},`),
		'} as const);',
	].join('\n');
};

/**
 * The tables and functions `sql` names that `declared` does not include and
 * the text does not define itself, each at the line of its first use.
 */
const undeclared = (
	sql: string,
	declared: DeclaredNames,
	holes: HoleDelimiters | undefined,
): ReadonlyArray<{ readonly line: number; readonly message: string }> => {
	const targets = analyzeTargets(lex(sql, holeDelimiters(holes)).tokens);
	const tables = new Set([...declared.tables, ...targets.definedTables]);
	const functions = new Set([
		...declared.functions,
		...targets.definedFunctions,
	]);
	const found: Array<{ line: number; message: string }> = [];
	const check = (
		at: ReadonlyMap<string, number>,
		known: ReadonlySet<string>,
		what: string,
	) => {
		for (const [name, line] of at)
			if (!known.has(name))
				found.push({
					line,
					message: `${what} \`${name}\`, which the schema does not declare`,
				});
	};
	check(targets.readAt, tables, 'reads table');
	check(targets.writtenAt, tables, 'writes table');
	check(targets.functionsAt, functions, 'calls function');
	return found.sort((a, b) => a.line - b.line);
};

/**
 * {@link renderStatementModules}, throwing its
 * {@link StatementModulesError}.
 */
export const renderStatementModulesSync = (
	input: RenderStatementModulesInput,
): StatementModules => {
	const problems: StatementProblem[] = [];
	const warnings: StatementWarning[] = [];
	const byScope = new Map<string, string[]>();
	const imports = new Map<string, Set<string>>();
	const scopes = new Map<string, string>();
	const names = new Map<string, Map<string, string>>();
	const sources = input.scopes.flatMap((scope) =>
		scope.files.map((file) => ({
			scope: scope.name,
			declared: scope.declared,
			name: file.name,
			sql: file.sql,
		})),
	);
	for (const source of sources.sort((a, b) =>
		a.scope === b.scope
			? a.name < b.name
				? -1
				: 1
			: a.scope < b.scope
				? -1
				: 1,
	)) {
		const file = `${source.scope}/${source.name}.surql`;
		if (!byScope.has(source.scope)) {
			const problem = checkName(
				source.scope,
				`scope ${JSON.stringify(source.scope)}`,
				scopes,
			);
			if (problem !== undefined) {
				problems.push({
					kind: 'scope',
					scope: source.scope,
					message: problem,
					text: `${source.scope}: ${problem}`,
				});
				continue;
			}
			byScope.set(source.scope, []);
		}
		const seen = names.get(source.scope) ?? new Map<string, string>();
		names.set(source.scope, seen);
		const problem = checkName(
			source.name,
			`file name ${JSON.stringify(source.name)}`,
			seen,
		);
		if (problem !== undefined) {
			problems.push({
				kind: 'name',
				scope: source.scope,
				file: source.name,
				message: problem,
				text: `${file}: ${problem}`,
			});
			continue;
		}
		let analysis: Analysis;
		try {
			analysis = analyzeSync(source.sql, {
				...(input.holes !== undefined && { holes: input.holes }),
			});
		} catch (error) {
			if (error instanceof AnalyzeError) {
				problems.push({
					kind: 'analysis',
					scope: source.scope,
					file: source.name,
					line: error.line,
					column: error.column,
					code: error.code,
					message: error.message,
					text: `${file}:${error.line}:${error.column}: ${error.message}`,
				});
				continue;
			}
			throw error;
		}
		let binds: Readonly<Record<string, string>> | undefined;
		let rejectsNone: Readonly<Record<string, RejectedNone>> | undefined;
		if (source.declared !== undefined) {
			const detail = source.declared.detail;
			const checked =
				detail === undefined
					? undefined
					: checkUses(
							analysis.uses,
							detail,
							changesSchema(source.sql, input.holes),
						);
			binds = checked?.binds;
			rejectsNone = checked?.rejectsNone;
			for (const problem of [
				...undeclared(source.sql, source.declared, input.holes),
				...(checked?.problems ?? []),
			].sort((a, b) => a.line - b.line))
				problems.push({
					kind: 'undeclared',
					scope: source.scope,
					file: source.name,
					line: problem.line,
					message: problem.message,
					text: `${file}:${problem.line}: ${problem.message}`,
				});
		}
		for (const diagnostic of analysis.diagnostics) {
			const at = {
				scope: source.scope,
				file: source.name,
				line: diagnostic.line,
				column: diagnostic.column,
				code: diagnostic.code,
				message: diagnostic.message,
				text: `${file}:${diagnostic.line}:${diagnostic.column}: ${diagnostic.message} (${diagnostic.code})`,
			};
			if (diagnostic.severity === 'error')
				problems.push({ kind: 'analysis', ...at });
			else warnings.push(at);
		}
		const used = imports.get(source.scope) ?? new Set();
		used.add(
			analysis.kind === 'part' && analysis.holes.length === 0
				? 'statement'
				: 'analyze',
		);
		imports.set(source.scope, used);
		const constants = byScope.get(source.scope) ?? [];
		constants.push(
			renderConstant(
				source.scope,
				source.name,
				analysis,
				binds,
				rejectsNone,
			),
		);
		byScope.set(source.scope, constants);
	}
	if (problems.length > 0) {
		const unique = new Map<string, StatementProblem>();
		for (const problem of problems)
			if (!unique.has(problem.text)) unique.set(problem.text, problem);
		throw new StatementModulesError({
			problems: [...unique.values()],
			message: [...unique.keys()].join('\n'),
		});
	}
	const files: StatementModule[] = [];
	for (const [scope, constants] of byScope) {
		const used = imports.get(scope) ?? new Set();
		files.push({
			path: `${scope}/statements.ts`,
			content: [
				STATEMENTS_MARK,
				'',
				...(used.has('analyze')
					? ['import * as $analyze from "effect-surrealkit/analyze";']
					: []),
				...(used.has('statement')
					? [
							'import * as $statement from "effect-surrealkit/statement";',
						]
					: []),
				'',
				constants.join('\n\n'),
				'',
			].join('\n'),
		});
	}
	const extension = input.importExtension ?? '.js';
	files.push({
		path: 'index.ts',
		content: [
			STATEMENTS_MARK,
			'',
			...[...byScope.keys()].map(
				(scope) =>
					`export * as ${scope} from "./${scope}/statements${extension}";`,
			),
			'',
		].join('\n'),
	});
	return { files, warnings };
};

/**
 * Renders the typed statement modules for these scopes: `<scope>/statements.ts`
 * for each scope, then `index.ts`, exactly as `effect-surrealkit statements`
 * writes them, with the analyzer's warnings. Fails with every problem: a
 * file the analyzer rejects, an invalid, reserved or case-colliding file
 * name, an invalid scope name, and, for a scope with `declared` names, a
 * table or function the schema does not declare. Reads and writes nothing.
 */
export const renderStatementModules = (
	input: RenderStatementModulesInput,
): Effect.Effect<StatementModules, StatementModulesError> =>
	Effect.suspend(() => {
		try {
			return Effect.succeed(renderStatementModulesSync(input));
		} catch (error) {
			if (error instanceof StatementModulesError)
				return Effect.fail(error);
			throw error;
		}
	});
