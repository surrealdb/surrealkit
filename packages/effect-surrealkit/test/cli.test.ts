import {
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { run } from '../src/cli/run.js';
import {
	at,
	examplePath,
	goldenDir,
	readJson,
	withoutToolVersionsIn,
} from './documents.js';

const dirs: string[] = [];
const tempDir = () => {
	const dir = mkdtempSync(join(tmpdir(), 'effect-surrealkit-'));
	dirs.push(dir);
	return dir;
};
afterEach(() => {
	for (const dir of dirs.splice(0))
		rmSync(dir, { recursive: true, force: true });
});

const cli = async (
	argv: string[],
	options: {
		cwd?: string;
		stdin?: string;
		env?: Record<string, string>;
	} = {},
) => {
	let stdout = '';
	let stderr = '';
	const code = await run(argv, {
		cwd: options.cwd ?? tempDir(),
		stdin: async () => options.stdin ?? '',
		...(options.env !== undefined && { env: options.env }),
		stdout: (text) => {
			stdout += text;
		},
		stderr: (text) => {
			stderr += text;
		},
	});
	return { code, stdout, stderr };
};

const filesOf = (dir: string) =>
	Object.fromEntries(
		readdirSync(dir)
			.sort()
			.map((file) => [file, readFileSync(join(dir, file), 'utf8')]),
	);

// Compared without the versions of the tools that wrote them (see documents.ts).
const golden = withoutToolVersionsIn(filesOf(goldenDir('example')));

describe('effect-surrealkit CLI', () => {
	it('writes the module set for a document file', async () => {
		const cwd = tempDir();
		const result = await cli(
			['--input', examplePath, '--out', 'gen', '--store', 'corpus'],
			{ cwd },
		);
		expect(result.stderr).toMatch(/9 modules in .*gen \(9 updated\)/);
		expect(result.code).toBe(0);
		expect(withoutToolVersionsIn(filesOf(join(cwd, 'gen')))).toEqual(
			golden,
		);
	});

	it('reads the document from stdin and options from --config', async () => {
		const cwd = tempDir();
		writeFileSync(
			join(cwd, 'emit.json'),
			JSON.stringify({ store: 'corpus' }),
		);
		const result = await cli(['--out', 'gen', '--config', 'emit.json'], {
			cwd,
			stdin: readFileSync(examplePath, 'utf8'),
		});
		expect(result.code).toBe(0);
		expect(withoutToolVersionsIn(filesOf(join(cwd, 'gen')))).toEqual(
			golden,
		);
	});

	it('is deterministic across working directories', async () => {
		const [a, b] = [tempDir(), tempDir()];
		mkdirSync(join(b, 'nested', 'deeper'), { recursive: true });
		await cli(
			['--input', examplePath, '--out', 'out', '--store', 'corpus'],
			{ cwd: a },
		);
		await cli(
			['--input', examplePath, '--out', '../../out', '--store', 'corpus'],
			{ cwd: join(b, 'nested', 'deeper') },
		);
		expect(filesOf(join(b, 'out'))).toEqual(filesOf(join(a, 'out')));
	});

	it('leaves unchanged files untouched and reports it', async () => {
		const cwd = tempDir();
		const args = [
			'--input',
			examplePath,
			'--out',
			'gen',
			'--store',
			'corpus',
		];
		await cli(args, { cwd });
		const before = statSync(join(cwd, 'gen', 'person.ts')).mtimeMs;
		const again = await cli(args, { cwd });
		expect(again.stderr).toMatch(/\(unchanged\)/);
		expect(statSync(join(cwd, 'gen', 'person.ts')).mtimeMs).toBe(before);
	});

	it('--check fails on missing, edited and stale files, and passes when up to date', async () => {
		const cwd = tempDir();
		const args = [
			'--input',
			examplePath,
			'--out',
			'gen',
			'--store',
			'corpus',
		];
		const missing = await cli([...args, '--check'], { cwd });
		expect(missing.code).toBe(1);
		expect(missing.stderr).toMatch(/missing: person\.ts/);

		await cli(args, { cwd });
		expect((await cli([...args, '--check'], { cwd })).code).toBe(0);

		const person = join(cwd, 'gen', 'person.ts');
		writeFileSync(
			person,
			readFileSync(person, 'utf8').replace(
				'Schema.Struct',
				'Schema.Struct /* edited */',
			),
		);
		writeFileSync(
			join(cwd, 'gen', 'old.ts'),
			'// Generated by effect-surrealkit from a SurrealKit schema document. Do not edit.\n',
		);
		writeFileSync(join(cwd, 'gen', 'mine.ts'), 'export const mine = 1;\n');
		const drift = await cli([...args, '--check'], { cwd });
		expect(drift.code).toBe(1);
		expect(drift.stderr).toMatch(/out of date or edited: person\.ts/);
		expect(drift.stderr).toMatch(/stale: old\.ts/);
		expect(drift.stderr).not.toMatch(/mine\.ts/);
		expect(readFileSync(person, 'utf8')).toMatch(/edited/); // --check writes nothing

		await cli(args, { cwd });
		const after = filesOf(join(cwd, 'gen'));
		expect(after['old.ts']).toBeUndefined(); // stale generated file removed
		expect(after['mine.ts']).toBe('export const mine = 1;\n'); // hand-written file kept
		expect(after['person.ts']).toBe(golden['person.ts']);
	});

	it('fails with exit 1 and a reason on an invalid or mismatched document', async () => {
		const cwd = tempDir();
		const invalid = await cli(['--out', 'gen', '--store', 'corpus'], {
			cwd,
			stdin: '{"version": 3}',
		});
		expect(invalid.code).toBe(1);
		expect(invalid.stderr).toMatch(/not a valid schema document v2/);

		const edited = readJson(examplePath);
		at(edited.tables as Array<Record<string, unknown>>, 0).comment =
			'hand edit';
		const mismatch = await cli(['--out', 'gen', '--store', 'corpus'], {
			cwd,
			stdin: JSON.stringify(edited),
		});
		expect(mismatch.code).toBe(1);
		expect(mismatch.stderr).toMatch(/semanticDigest mismatch/);
		expect(() => readdirSync(join(cwd, 'gen'))).toThrow(); // nothing written
	});

	it('takes acknowledgements from the command line', async () => {
		const document = readJson(examplePath);
		(document.diagnostics as unknown[]).push({
			severity: 'error',
			code: 'structure-unknown-key',
			source: 'mystery',
			reason: 'STRUCTURE returned a key the adapter does not map.',
		});
		const stdin = JSON.stringify(document);
		const refused = await cli(['--out', 'gen', '--store', 'corpus'], {
			stdin,
		});
		expect(refused.code).toBe(1);
		expect(refused.stderr).toMatch(/structure-unknown-key/);
		const accepted = await cli(
			[
				'--out',
				'gen',
				'--store',
				'corpus',
				'--acknowledge',
				'structure-unknown-key=known 3.3.1 key',
			],
			{ stdin },
		);
		expect(accepted.code).toBe(0);
	});

	it('exits 2 on bad arguments and prints usage', async () => {
		const unknown = await cli(['--bogus']);
		expect(unknown.code).toBe(2);
		expect(unknown.stderr).toMatch(/Usage: effect-surrealkit/);
		const noOut = await cli(['--store', 'corpus']);
		expect(noOut.code).toBe(2);
		expect(noOut.stderr).toMatch(/--out <dir> is required/);
		const badAck = await cli(['--out', 'x', '--acknowledge', 'nope'], {
			stdin: '{}',
		});
		expect(badAck.code).toBe(2);
	});

	it('prints help and version', async () => {
		expect((await cli(['--help'])).stdout).toMatch(
			/Usage: effect-surrealkit/,
		);
		expect((await cli(['--version'])).stdout).toBe(
			`${readJson(join(import.meta.dirname, '..', 'package.json')).version}\n`,
		);
	});

	describe('as a SurrealKit external emitter (protocol 1)', () => {
		const env = {
			SURREALKIT_EMIT_PROTOCOL: '1',
			SURREALKIT_EMIT_NAME: 'effect',
			SURREALKIT_EMIT_OUT: 'src/generated',
		};
		const stdin = () => readFileSync(examplePath, 'utf8');

		it('prints the reply with every generated file and writes nothing', async () => {
			const cwd = tempDir();
			const result = await cli(['--store', 'corpus'], {
				cwd,
				stdin: stdin(),
				env,
			});
			expect(result.code, result.stderr).toBe(0);
			expect(result.stdout.endsWith('\n')).toBe(true);
			const reply = JSON.parse(result.stdout) as {
				protocol: number;
				files: Array<{ path: string; contents: string }>;
			};
			expect(Object.keys(reply)).toEqual(['protocol', 'files']);
			expect(reply.protocol).toBe(1);
			expect(
				withoutToolVersionsIn(
					Object.fromEntries(
						reply.files.map((file) => [file.path, file.contents]),
					),
				),
			).toEqual(golden);
			expect(readdirSync(cwd)).toEqual([]);
			// The document's own diagnostics are SurrealKit's to report.
			expect(result.stderr).not.toMatch(/warning: document:/);
		});

		it('refuses --out, --input and --check, and an unknown protocol', async () => {
			for (const flag of [
				['--out', 'x'],
				['--input', examplePath],
				['--check'],
			]) {
				const result = await cli(['--store', 'corpus', ...flag], {
					stdin: stdin(),
					env,
				});
				expect(result.code).toBe(2);
				expect(result.stderr).toMatch(/SurrealKit/);
			}
			const future = await cli(['--store', 'corpus'], {
				stdin: stdin(),
				env: { ...env, SURREALKIT_EMIT_PROTOCOL: '2' },
			});
			expect(future.code).toBe(1);
			expect(future.stderr).toMatch(/speaks protocol 1/);
			expect(future.stdout).toBe('');
		});

		it("honours the project's [typegen] acknowledge", async () => {
			const document = readJson(examplePath);
			(document.diagnostics as unknown[]).push({
				severity: 'error',
				code: 'structure-unknown-key',
				source: 'mystery',
				reason: 'STRUCTURE returned a key the adapter does not map.',
			});
			const input = JSON.stringify(document);
			const refused = await cli(['--store', 'corpus'], {
				stdin: input,
				env,
			});
			expect(refused.code).toBe(1);
			expect(refused.stdout).toBe('');
			const accepted = await cli(['--store', 'corpus'], {
				stdin: input,
				env: {
					...env,
					SURREALKIT_EMIT_ACKNOWLEDGE: JSON.stringify({
						'structure-unknown-key': 'known 3.3.1 key',
					}),
				},
			});
			expect(accepted.code, accepted.stderr).toBe(0);
			for (const bad of ['[]', '{"x": ""}', 'nope']) {
				const result = await cli(['--store', 'corpus'], {
					stdin: input,
					env: { ...env, SURREALKIT_EMIT_ACKNOWLEDGE: bad },
				});
				expect(result.code, bad).toBe(2);
				expect(result.stdout).toBe('');
			}
		});

		it('fails with nothing on stdout when generation fails', async () => {
			const result = await cli([], { stdin: stdin(), env });
			expect(result.code).toBe(1);
			expect(result.stdout).toBe('');
			expect(result.stderr).toMatch(/store/);
		});
	});
});
