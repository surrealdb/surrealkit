import {
	cpSync,
	existsSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { run } from '../src/cli/run.js';
import { renderStatements, StatementsError } from '../src/cli/statements.js';
import { goldenDir } from './documents.js';

const fixtures = join(import.meta.dirname, 'fixtures', 'statements');
const golden = goldenDir('statements');

const dirs: string[] = [];
const tempDir = () => {
	const dir = mkdtempSync(join(tmpdir(), 'effect-surrealkit-statements-'));
	dirs.push(dir);
	return dir;
};
afterEach(() => {
	for (const dir of dirs.splice(0))
		rmSync(dir, { recursive: true, force: true });
});

const cli = async (argv: string[], cwd: string, signal?: AbortSignal) => {
	let stdout = '';
	let stderr = '';
	const code = await run(['statements', ...argv], {
		cwd,
		stdin: async () => '',
		...(signal !== undefined && { signal }),
		stdout: (text) => {
			stdout += text;
		},
		stderr: (text) => {
			stderr += text;
		},
	});
	return { code, stdout, stderr };
};

/** Every file under `dir`, by relative path. */
const tree = (dir: string, prefix = ''): Record<string, string> =>
	Object.fromEntries(
		readdirSync(dir, { withFileTypes: true })
			.sort((a, b) => (a.name < b.name ? -1 : 1))
			.flatMap((entry) =>
				entry.isDirectory()
					? Object.entries(
							tree(
								join(dir, entry.name),
								`${prefix}${entry.name}/`,
							),
						)
					: [
							[
								`${prefix}${entry.name}`,
								readFileSync(join(dir, entry.name), 'utf8'),
							],
						],
			),
	);

/** A copy of the fixtures to change. */
const input = () => {
	const dir = tempDir();
	cpSync(fixtures, join(dir, 'queries'), { recursive: true });
	return dir;
};

describe('effect-surrealkit statements', () => {
	it('the golden modules are what the fixtures generate', async () => {
		if (process.env.UPDATE_GOLDEN === '1') {
			rmSync(golden, { recursive: true, force: true });
			const written = await cli(
				['--input', fixtures, '--out', golden],
				import.meta.dirname,
			);
			expect(written.code, written.stderr).toBe(0);
		}
		const result = await cli(
			['--input', fixtures, '--out', golden, '--check'],
			import.meta.dirname,
		);
		expect(result.code, result.stderr).toBe(0);
	});

	it('writes one module per scope and an index, deterministically', async () => {
		const [a, b] = [input(), input()];
		const first = await cli(['--input', 'queries', '--out', 'gen'], a);
		expect(first.code, first.stderr).toBe(0);
		expect(first.stderr).toMatch(/4 modules in .*gen \(4 updated\)/);
		await cli(['--input', 'queries', '--out', 'gen'], b);
		expect(tree(join(a, 'gen'))).toEqual(tree(join(b, 'gen')));
		expect(tree(join(a, 'gen'))).toEqual(tree(golden));
		const index = readFileSync(join(a, 'gen', 'index.ts'), 'utf8');
		expect(index).toMatch(
			/^\/\/ Generated by effect-surrealkit from SurrealQL files\. Do not edit\./,
		);
		expect(index).toMatch(
			/export \* as accounts from "\.\/accounts\/statements\.js";/,
		);
		const ts = await cli(
			[
				'--input',
				'queries',
				'--out',
				'gen-ts',
				'--import-extension',
				'.ts',
			],
			a,
		);
		expect(ts.code).toBe(0);
		expect(readFileSync(join(a, 'gen-ts', 'index.ts'), 'utf8')).toMatch(
			/"\.\/accounts\/statements\.ts"/,
		);
	});

	it('writes a part with its derived facts, and fragments and templates as text', () => {
		const accounts = readFileSync(
			join(golden, 'accounts', 'statements.ts'),
			'utf8',
		);
		expect(accounts).toContain(
			[
				'export const bindOwner = $statement.part({',
				'\tname: "accounts.bindOwner",',
				'\tsource: "accounts/bindOwner.surql",',
			].join('\n'),
		);
		expect(accounts).toContain('\tfree: ["boundOwner"],');
		expect(accounts).toContain('\tdefines: ["owner", "principal"],');
		expect(accounts).toContain('\tthrowsAt: { "Not the owner": [1] },');
		expect(accounts).toContain(
			'export const ownerFilter = $analyze.text({',
		);
		expect(accounts).toContain('\tsql: `owner = $owner`,');
		expect(accounts).toContain('\tholes: ["__FILTER__"],');
		expect(accounts).toContain('\tprovisional: true,');
	});

	it('leaves unchanged files untouched', async () => {
		const cwd = input();
		const args = ['--input', 'queries', '--out', 'gen'];
		await cli(args, cwd);
		const path = join(cwd, 'gen', 'accounts', 'statements.ts');
		const before = statSync(path).mtimeMs;
		const again = await cli(args, cwd);
		expect(again.stderr).toMatch(/\(unchanged\)/);
		expect(statSync(path).mtimeMs).toBe(before);
	});

	it('--check fails on missing, edited and stale files and writes nothing; generation removes stale files only', async () => {
		const cwd = input();
		const args = ['--input', 'queries', '--out', 'gen'];
		const missing = await cli([...args, '--check'], cwd);
		expect(missing.code).toBe(1);
		expect(missing.stderr).toMatch(/missing: accounts\/statements\.ts/);
		expect(existsSync(join(cwd, 'gen'))).toBe(false);

		await cli(args, cwd);
		expect((await cli([...args, '--check'], cwd)).code).toBe(0);

		const path = join(cwd, 'gen', 'counter', 'statements.ts');
		writeFileSync(path, `${readFileSync(path, 'utf8')}// edited\n`);
		// A scope removed from the input leaves a stale module.
		mkdirSync(join(cwd, 'gen', 'old'));
		writeFileSync(
			join(cwd, 'gen', 'old', 'statements.ts'),
			'// Generated by effect-surrealkit from SurrealQL files. Do not edit.\n',
		);
		writeFileSync(join(cwd, 'gen', 'mine.ts'), 'export const mine = 1;\n');
		const drift = await cli([...args, '--check'], cwd);
		expect(drift.code).toBe(1);
		expect(drift.stderr).toMatch(
			/out of date or edited: counter\/statements\.ts/,
		);
		expect(drift.stderr).toMatch(/stale: old\/statements\.ts/);
		expect(drift.stderr).not.toMatch(/mine\.ts/);
		expect(readFileSync(path, 'utf8')).toMatch(/edited/);

		expect((await cli(args, cwd)).code).toBe(0);
		const after = tree(join(cwd, 'gen'));
		expect(after['old/statements.ts']).toBeUndefined();
		expect(existsSync(join(cwd, 'gen', 'old'))).toBe(false);
		expect(after['mine.ts']).toBe('export const mine = 1;\n');
		expect(after['counter/statements.ts']).toBe(
			tree(golden)['counter/statements.ts'],
		);
	});

	it('never overwrites a file it did not generate', async () => {
		const cwd = input();
		mkdirSync(join(cwd, 'gen', 'accounts'), { recursive: true });
		const path = join(cwd, 'gen', 'accounts', 'statements.ts');
		writeFileSync(path, 'export const handWritten = 1;\n');
		const result = await cli(['--input', 'queries', '--out', 'gen'], cwd);
		expect(result.code).toBe(1);
		expect(result.stderr).toMatch(/refusing to overwrite.*\n.*accounts/);
		expect(readFileSync(path, 'utf8')).toBe(
			'export const handWritten = 1;\n',
		);
	});

	it('fails with file, line and column on an analysis error or an error diagnostic, writing nothing', async () => {
		const cwd = input();
		writeFileSync(
			join(cwd, 'queries', 'counter', 'broken.surql'),
			"RETURN 1;\nRETURN 'open;\n",
		);
		writeFileSync(
			join(cwd, 'queries', 'counter', 'spoof.surql'),
			'BEGIN;\nLET $auth = 1;\nRETURN 1;\n2;\nCOMMIT;\n',
		);
		const result = await cli(['--input', 'queries', '--out', 'gen'], cwd);
		expect(result.code).toBe(1);
		expect(result.stderr).toMatch(
			/counter\/broken\.surql:2:8: unterminated string/,
		);
		expect(result.stderr).toMatch(
			/counter\/spoof\.surql:2:5: .*\(protectedLet\)/,
		);
		expect(result.stderr).toMatch(
			/counter\/spoof\.surql:3:1: .*\(returnInTransaction\)/,
		);
		expect(existsSync(join(cwd, 'gen'))).toBe(false);
	});

	it('prints warnings and still generates', async () => {
		const cwd = input();
		writeFileSync(
			join(cwd, 'queries', 'counter', 'dynamic.surql'),
			"THROW string::concat('x', $y);\n",
		);
		const result = await cli(['--input', 'queries', '--out', 'gen'], cwd);
		expect(result.code).toBe(0);
		expect(result.stderr).toMatch(
			/warning: counter\/dynamic\.surql:1:1: .*\(dynamicThrow\)/,
		);
	});

	it.each([
		['class.surql', /reserved word/],
		['not-a-name.surql', /not a JavaScript identifier/],
		['notes.txt', /holds only \.surql files/],
	])('refuses the file %s', async (file, reason) => {
		const cwd = input();
		writeFileSync(join(cwd, 'queries', 'counter', file), 'RETURN 1;\n');
		const result = await cli(['--input', 'queries', '--out', 'gen'], cwd);
		expect(result.code).toBe(1);
		expect(result.stderr).toMatch(reason);
	});

	it('refuses names that differ only in case, whatever the file system', () => {
		const render = (
			sources: ReadonlyArray<{ scope: string; name: string }>,
		) => {
			try {
				renderStatements(
					sources.map((source) => ({ ...source, sql: 'RETURN 1;' })),
					{ importExtension: '.js' },
				);
			} catch (error) {
				if (error instanceof StatementsError) return error.message;
				throw error;
			}
			return '';
		};
		expect(
			render([
				{ scope: 'a', name: 'step' },
				{ scope: 'a', name: 'Step' },
				{ scope: 'b', name: 'step' },
			]),
		).toBe(
			'a/step.surql: file name "step" differs only in case from "Step"',
		);
		expect(
			render([
				{ scope: 'Accounts', name: 'x' },
				{ scope: 'accounts', name: 'x' },
				{ scope: 'accounts', name: 'y' },
			]),
		).toBe(
			'accounts: scope "accounts" differs only in case from "Accounts"',
		);
	});

	it('refuses a file at the top of --input and a nested directory', async () => {
		const cwd = input();
		writeFileSync(join(cwd, 'queries', 'loose.surql'), 'RETURN 1;\n');
		mkdirSync(join(cwd, 'queries', 'counter', 'nested'));
		const result = await cli(['--input', 'queries', '--out', 'gen'], cwd);
		expect(result.code).toBe(1);
		expect(result.stderr).toMatch(/loose\.surql: --input holds only scope/);
		expect(result.stderr).toMatch(/counter\/nested: a scope holds only/);
	});

	it('takes literal hole delimiters', async () => {
		const cwd = input();
		writeFileSync(
			join(cwd, 'queries', 'counter', 'limited.surql'),
			'SELECT * FROM t LIMIT {{LIMIT}};\n',
		);
		const result = await cli(
			[
				'--input',
				'queries',
				'--out',
				'gen',
				'--hole-open',
				'{{',
				'--hole-close',
				'}}',
			],
			cwd,
		);
		expect(result.code, result.stderr).toBe(0);
		expect(
			readFileSync(join(cwd, 'gen', 'counter', 'statements.ts'), 'utf8'),
		).toContain('\tholes: ["{{LIMIT}}"],');
	});

	it('exits 2 on bad arguments', async () => {
		const cwd = input();
		for (const argv of [
			['--out', 'gen'],
			['--input', 'queries'],
			[
				'--input',
				'queries',
				'--out',
				'gen',
				'--import-extension',
				'.mjs',
			],
			['--input', 'queries', '--out', 'gen', '--hole-open', ''],
			['--input', 'queries', '--out', 'gen', '--hole-close', 'a b'],
			['--input', 'queries', '--out', 'gen', '--hole-pattern', '('],
			['--input', 'queries', '--out', 'queries/gen'],
			['--input', 'queries', '--out', 'gen', '--check', '--watch'],
			['--bogus'],
		]) {
			const result = await cli(argv, cwd);
			expect(result.code, argv.join(' ')).toBe(2);
			expect(result.stderr).toMatch(
				/Usage: effect-surrealkit statements/,
			);
		}
		expect((await cli(['--help'], cwd)).stdout).toMatch(
			/Usage: effect-surrealkit statements/,
		);
	});

	it('--watch regenerates on change until stopped', async () => {
		const cwd = input();
		const controller = new AbortController();
		let stderr = '';
		const watching = run(
			['statements', '--input', 'queries', '--out', 'gen', '--watch'],
			{
				cwd,
				stdin: async () => '',
				stdout: () => undefined,
				stderr: (text) => {
					stderr += text;
				},
				signal: controller.signal,
			},
		);
		const until = async (check: () => boolean) => {
			for (let i = 0; i < 200 && !check(); i++)
				await new Promise((resolve) => setTimeout(resolve, 25));
			expect(check(), stderr).toBe(true);
		};
		const module = join(cwd, 'gen', 'counter', 'statements.ts');
		await until(() => stderr.includes('watching'));
		writeFileSync(
			join(cwd, 'queries', 'counter', 'added.surql'),
			'RETURN $added;\n',
		);
		await until(() =>
			readFileSync(module, 'utf8').includes('export const added'),
		);
		// An error is reported and watching goes on.
		writeFileSync(
			join(cwd, 'queries', 'counter', 'added.surql'),
			"RETURN 'open;\n",
		);
		await until(() => stderr.includes('added.surql:1:8'));
		controller.abort();
		expect(await watching).toBe(0);
	});
});
